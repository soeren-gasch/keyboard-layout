"""Leser für die Code-Korpora (Quelltext aus freien Repositories).

Eine Quelle ist eine Sprache (code-php, code-vue, code-javascript, code-java, code-sql). Welche Archive dazugehören,
steht im Manifest korpora/code/quellen.json (Feld genutzt_von). Jede Datei wird als Einheit im Modus "datei" geliefert
(siehe normalisierung_code.py).

Auswahl der Dateien je Archiv:
- nur die Endungen der Sprache, keine Verzeichnisse wie vendor, node_modules, dist, build, versteckte Ordner,
  keine Übersetzungsordner (lang, locales, i18n …) außer dem englischen;
- keine Dateien über 300 KB, keine minifizierten oder generierten Dateien;
- der Lizenzkopf am Dateianfang wird entfernt;
- hat ein Archiv mehr geeignete Bytes als `cap_je_repo`, wird deterministisch ein Teil der Dateien gewählt (über die
  CRC32-Prüfsumme des Pfads), damit einzelne große Repositories eine Sprache nicht dominieren.
"""

import json
import re
import tarfile
import zlib
from pathlib import Path

import quellen as _q

ORIGINAL_CODE = Path(__file__).resolve().parent.parent / "code" / "original"

ENDUNGEN = {
    "code-php": (".php",),
    "code-vue": (".vue",),
    "code-javascript": (".js", ".mjs", ".cjs"),
    "code-java": (".java",),
    "code-sql": (".sql",),
}
AUSSCHLUSS_VERZEICHNISSE = {
    "vendor", "node_modules", "dist", "build", "target", "bower_components", "third_party", "thirdparty",
    "third-party", "cache", "generated", "__snapshots__", "coverage",
}
ZUSATZ_AUSSCHLUSS = {"code-javascript": {"fixtures", "__fixtures__"}, "code-vue": {"fixtures", "__fixtures__"}}
# Übersetzungsordner: fremdsprachige Texte in Code wären Prosa einer anderen Sprache; nur Englisch bleibt.
UEBERSETZUNGSVERZEICHNISSE = {"lang", "langs", "locale", "locales", "i18n", "l10n", "translations", "language", "languages"}
ENGLISCH = {"en", "en-us", "en_us", "en-gb", "en_gb", "english"}
MAX_DATEIGROESSE = 300_000
MAX_MITTLERE_ZEILENLAENGE = 160

_LIZENZ = re.compile(r"copyright|licen[sc]e|licensed|permission is hereby granted|spdx-license|all rights reserved|\(c\)",
                     re.I)
_KOPF = re.compile(
    r"(\s*(?:<\?php\s*)?)(/\*.*?\*/|(?://[^\n]*\n)+|(?:#[^\n]*\n)+|(?:--[^\n]*\n)+|<!--.*?-->)", re.S)
_GENERIERT = ("@generated", "do not edit", "auto-generated", "autogenerated", "this file was generated",
              "generated by", "code generated")


def _geeignet(name, groesse, quelle):
    teile = name.split("/")[1:]  # erstes Element ist das Oberverzeichnis des Archivs
    if not teile or groesse < 40 or groesse > MAX_DATEIGROESSE:
        return False
    ausschluss = AUSSCHLUSS_VERZEICHNISSE | ZUSATZ_AUSSCHLUSS.get(quelle, set())
    if any(t in ausschluss or t.startswith(".") for t in teile[:-1]):
        return False
    for i, teil in enumerate(teile[:-1]):
        if teil.lower() in UEBERSETZUNGSVERZEICHNISSE and teile[i + 1].lower().split(".")[0] not in ENGLISCH:
            return False
    datei = teile[-1]
    if not datei.endswith(ENDUNGEN[quelle]) or datei.startswith("."):
        return False
    return not (".min." in datei or datei.endswith(("-min.js", ".bundle.js")))


def _ohne_lizenzkopf(text, stat):
    m = _KOPF.match(text)
    if m and len(m.group(2)) < 5000 and _LIZENZ.search(m.group(2)):
        stat["lizenzkopf_entfernt"] += 1
        return m.group(1) + text[m.end():]
    return text


def _repo(e, quelle, cap, stat):
    repo = e.get("repo") or e["pfad"]
    with tarfile.open(e["ziel"], "r:gz") as tar:
        geeignet = sum(m.size for m in tar if m.isfile() and _geeignet(m.name, m.size, quelle))
    rate = min(1.0, cap / geeignet) if geeignet else 0.0
    stat[f"detail:{repo}:geeignet_bytes"] = geeignet
    stat[f"detail:{repo}:anteil_promille"] = round(rate * 1000)
    with tarfile.open(e["ziel"], "r:gz") as tar:
        for m in tar:
            if not (m.isfile() and _geeignet(m.name, m.size, quelle)):
                continue
            rel = m.name.split("/", 1)[1]
            if zlib.crc32(rel.encode("utf-8")) % 10000 >= rate * 10000:
                continue
            text = tar.extractfile(m).read().decode("utf-8", "replace")
            kopf = text[:600].lower()
            if any(k in kopf for k in _GENERIERT):
                stat["datei_verworfen:generiert"] += 1
                continue
            zeilen = text.count("\n") + 1
            if len(text) > 2000 and len(text) / zeilen > MAX_MITTLERE_ZEILENLAENGE:
                stat["datei_verworfen:minifiziert"] += 1
                continue
            stat["einheiten_gelesen"] += 1
            stat[f"detail:{repo}:dateien"] += 1
            stat[f"detail:{repo}:zeichen_roh"] += len(text)
            yield _ohne_lizenzkopf(text, stat), "datei"


def _sql_create_context(pfad, stat):
    gesehen = set()
    for z in json.loads(Path(pfad).read_text(encoding="utf-8")):
        text = f"{z['context']}\n{z['answer']}\n"
        if text in gesehen:
            stat["datei_verworfen:doppelt"] += 1
            continue
        gesehen.add(text)
        stat["einheiten_gelesen"] += 1
        stat["detail:b-mc2/sql-create-context:dateien"] += 1
        yield text, "datei"


def code(stat, quelle, cap_je_repo=10_000_000, **_):
    for e in sorted(_q.eingaben()[quelle], key=lambda x: x["pfad"]):
        if e["ziel"].name.endswith(".json"):
            yield from _sql_create_context(e["ziel"], stat)
        else:
            yield from _repo(e, quelle, cap_je_repo, stat)


